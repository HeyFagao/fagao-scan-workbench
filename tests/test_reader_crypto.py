"""Known-answer tests for the bundled public-reader format dependency."""

import hashlib
import json
from pathlib import Path
import unittest
from unittest.mock import patch

from fagao._vendor.pyaes import AESModeOfOperationCBC
from fagao.reader_crypto import decrypt_cbc


KEY = bytes.fromhex("2b7e151628aed2a6abf7158809cf4f3c")
IV = bytes.fromhex("000102030405060708090a0b0c0d0e0f")


class ReaderCryptoTests(unittest.TestCase):
    def test_nist_sp800_38a_cbc_known_answers_for_all_key_sizes(self):
        # NIST SP 800-38A, F.2.2, F.2.4, F.2.6; no padding in these vectors.
        # https://nvlpubs.nist.gov/nistpubs/Legacy/SP/nistspecialpublication800-38a.pdf
        plaintext = bytes.fromhex(
            "6bc1bee22e409f96e93d7e117393172a"
            "ae2d8a571e03ac9c9eb76fac45af8e51"
            "30c81c46a35ce411e5fbc1191a0a52ef"
            "f69f2445df4f9b17ad2b417be66c3710"
        )
        vectors = (
            (KEY.hex(),
             "7649abac8119b246cee98e9b12e9197d5086cb9b507219ee95db113a917678b2"
             "73bed6b8e3c1743b7116e69e222295163ff1caa1681fac09120eca307586e1a7"),
            ("8e73b0f7da0e6452c810f32b809079e562f8ead2522c6b7b",
             "4f021db243bc633d7178183a9fa071e8b4d9ada9ad7dedf4e5e738763f69145a"
             "571b242012fb7ae07fa9baac3df102e008b0e27988598881d920a9e64f5615cd"),
            ("603deb1015ca71be2b73aef0857d77811f352c073b6108d72d9810a30914dff4",
             "f58c4c04d6e5f1ba779eabfb5f7bfbd69cfc4e967edb808d679f777bc6702c7d"
             "39f23369a9d9bacfa530e26304231461b2eb05e2c39be9fcda6c19078c6a9d1b"),
        )
        for key_hex, cipher_hex in vectors:
            with self.subTest(bits=len(key_hex) * 4):
                mode = AESModeOfOperationCBC(bytes.fromhex(key_hex), iv=IV)
                cipher = bytes.fromhex(cipher_hex)
                decoded = b"".join(mode.decrypt(cipher[i:i + 16]) for i in range(0, len(cipher), 16))
                self.assertEqual(decoded, plaintext)

    def test_pkcs7_known_answers_from_independent_libressl(self):
        # Generated by LibreSSL 3.3.6 `openssl enc -aes-128-cbc -e` with
        # the public KEY/IV above. Tests require no executable or network.
        vectors = (
            (b"", "c84af0b613435d5d9182801a9bd9320b"),
            (b"public chapter", "5e445517c227dd2a345991ca40a41a53"),
            (b"0123456789abcdef", "64768548007aef9f3d258e5c34cdc21bde0a1268436e159434fc21de3696d928"),
            (b"Public chapter bytes across more than one block.",
             "d8a6658c11d95ba209204eff341c6eb629845455af9b9eee5b07467ded053a8771"
             "6c65a0de882f38116ad153bc8d8b8de6ec3b615ee0ffb757e2321051a1dd9c"),
        )
        for plaintext, cipher_hex in vectors:
            with self.subTest(length=len(plaintext)):
                self.assertEqual(decrypt_cbc(bytes.fromhex(cipher_hex), KEY, IV), plaintext)

    def test_rejects_zero_oversized_and_mismatched_padding(self):
        # Independently encrypted using LibreSSL 3.3.6 with -nopad:
        # b"0123456789abcde\x00", b"0123456789abcde\x11",
        # b"0123456789abcd\x01\x02". The last case catches permissive unpadding.
        for cipher_hex in (
            "9c91ebee369deb1db2f0b96cb79f039d",
            "48370ee60be2cf45445019df3490a938",
            "1a1a87f3eb6b86721cc4b9d755708176",
        ):
            with self.subTest(cipher=cipher_hex):
                with self.assertRaisesRegex(ValueError, "padding"):
                    decrypt_cbc(bytes.fromhex(cipher_hex), KEY, IV)

    def test_rejects_malformed_inputs_before_decryption(self):
        valid = bytes.fromhex("5e445517c227dd2a345991ca40a41a53")
        invalid = (
            (b"", KEY, IV), (b"x" * 15, KEY, IV),
            (valid, b"short", IV), (valid, KEY, b"short"),
            ("text", KEY, IV), (valid, "key", IV), (valid, KEY, "iv"),
            (bytearray(valid), KEY, IV),
        )
        with patch("fagao.reader_crypto.AESModeOfOperationCBC") as mode:
            for args in invalid:
                with self.subTest(types=tuple(type(x).__name__ for x in args)):
                    with self.assertRaises(ValueError):
                        decrypt_cbc(*args)
            mode.assert_not_called()

    def test_rejects_excessive_ciphertext_before_decryption(self):
        with patch("fagao.reader_crypto.MAX_CIPHERTEXT_BYTES", 16), patch(
            "fagao.reader_crypto.AESModeOfOperationCBC"
        ) as mode:
            with self.assertRaisesRegex(ValueError, "length"):
                decrypt_cbc(b"x" * 32, KEY, IV)
            mode.assert_not_called()

    def test_vendored_files_match_pinned_upstream_bytes(self):
        root = Path(__file__).resolve().parents[1]
        manifest = json.loads((root / "fagao/_vendor/pyaes/UPSTREAM.json").read_text(encoding="utf-8"))
        self.assertEqual(manifest["version"], "1.6.1")
        self.assertEqual(manifest["distribution_sha256"],
                         "02c1b1405c38d3c370b085fb952dd8bea3fadcee6411ad99f312cc129c536d8f")
        self.assertEqual(len(manifest["files"]), 5)
        for item in manifest["files"]:
            with self.subTest(path=item["local_path"]):
                raw = (root / item["local_path"]).read_bytes()
                self.assertEqual(len(raw), item["bytes"])
                self.assertEqual(hashlib.sha256(raw).hexdigest(), item["sha256"])
                self.assertTrue(item["unmodified"])


if __name__ == "__main__":
    unittest.main()
